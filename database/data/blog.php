If your solar system includes battery storage, choosing between lithium and lead-acid batteries is one of the most important decisions you will make. Both can work well, but they behave very differently.

Usable capacity

Lead-acid batteries last longer when they are not deeply discharged, so typically only part of their rated capacity is used regularly. Lithium iron phosphate (LiFePO4) batteries can use a much larger share of their rated capacity. In practice, a lead-acid bank usually needs a larger rated capacity to deliver the same usable energy.

Cycle life

LiFePO4 batteries generally withstand many more charge and discharge cycles than lead-acid batteries. The exact figures depend on the product, depth of discharge and operating temperature, so always check the manufacturer's datasheet.

Maintenance

Flooded lead-acid batteries, including many tubular batteries, need periodic checks of electrolyte level and should be installed in a ventilated space. Lithium batteries are sealed, maintenance-free and protected by a battery management system (BMS).

Efficiency and charging

Lithium batteries typically have higher round-trip efficiency, so more of the energy put in can be taken out again. They also accept charge faster. Charger settings must match the battery chemistry: settings designed for lead-acid batteries are not suitable for lithium batteries.


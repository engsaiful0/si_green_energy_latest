Net metering is an arrangement that allows a consumer with a grid-connected solar system to send surplus electricity to the utility grid and receive credit for it against the electricity they consume.

How net metering works

A grid-connected solar system supplies your loads first. When it produces more than you are using, the surplus flows into the grid. A bi-directional meter records both the electricity you import from the grid and the electricity you export. Your bill is then based on the net amount, according to the rules of the scheme.

Net metering in Bangladesh

Bangladesh's Power Division issued a Net Metering Guideline in 2018, with the Sustainable and Renewable Energy Development Authority (SREDA) involved in its implementation. The guideline enables eligible on-grid consumers to install rooftop solar and export surplus power to the grid.

Eligibility conditions, system size limits, application procedures and the treatment of exported energy are defined by the guideline and the distribution utilities. These details can change over time, so always confirm the current requirements with your distribution utility and SREDA before planning a project. SREDA also operates a national solar help desk for rooftop solar.

What you need for net metering

A grid-connected (on-grid or hybrid) solar system with a compliant inverter. An approved bi-directional meter installed by the utility. Approval of the application by the distribution utility.

Is net metering right for you?

Net metering is most useful when your solar system sometimes produces more than you use, for example on holidays or weekends. If your daytime consumption is always higher than your solar generation, you will use nearly all of your solar energy on site anyway.


Off-grid systems

An off-grid system works independently of the grid. Solar panels charge a battery bank, and an inverter supplies AC power from the batteries.

Off-grid systems need careful sizing, because the batteries and panels must cover your energy needs during cloudy periods too. Batteries add to the cost and eventually need replacement.

Best for: locations without a grid connection, remote sites and islands.

Hybrid systems

A hybrid system combines both approaches. It uses solar power first, stores surplus energy in batteries and uses the grid when needed. When the grid goes down, it keeps selected loads running from solar and battery power.

Best for: homes and businesses that want to reduce grid use and also need backup during power cuts, a common situation in Bangladesh.

How to choose

